#!/bin/sh -c exec${IFS}"${0%/*}/py"${IFS}"$0"${IFS}"$@"
"""The platform's MCP server (stdio): any coding agent that supports MCP can read and send project mail and write
memory notes (docs/design/tool-agnostic.md section 4).

  brunna mcp            run it (stdin/stdout carry MCP JSON-RPC, one message per line; logs go only to stderr)
  brunna mcp config     print the snippet to register in the tool's MCP settings (the platform does not change the
                          tool's settings for you)

Tools: inbox, show, thread, send, ack, pass, done (same names and meanings as `brunna`'s mailbox commands) + ask_owner
(ask the owner), note (written into this project's memory notes). Everything is handed to bin/hubbus (the same
implementation); the server only decides which project: environment variable AGENTHUB_PROJECT > working directory
(hubbus.project_of: worktrees and .agent-memory count as the main project). Project not recognised -> every tool
returns an error saying how to set it. A sandboxed project's mail goes through its outbox and view, as hubbus does
in its folder (docs/design/bus-sender.md).

The `instructions` returned by `initialize` carry the platform's rules (templates/mcp-instructions.md) and the number
of letters still open -- the rules reach any tool that supports MCP without changing any file in the project.

Presence (docs/design/mailbox-runtimes.md A3, class Presence): at `initialize` and at each tool call the server
records that its client uses the project, as mcp:<pid>:<start time> (a sandboxed project's through its outbox), so
the platform's dispatch holds a request for this session instead of sending another agent onto the project (hubbus
mcp_sessions); every tool result but inbox's ends with the number of letters still open, so the session knows.

A confined run the platform starts (docs/design/confined-mail-tools.md M3) gets this server attached by the platform
itself, with `--run <file>`: the run's own file in the platform's state, written by llm.py before the run starts and
read here once, before `initialize`. Its project is the file's alone (never one its environment or folder names),
its tools are the file's (a mail handler's, or a job's: only starting new letters), hubbus runs in the project's folder
with an environment built here (no platform variable inherited, the login's removed, the run's chain and letters
given), and hubbus holds it to the confined checks. A file that fails a check leaves the server answering, every call
refused with the reason. Any other agent the platform starts (HUB_LLM_POINT, set by llm.py, and no --run) is refused:
the letters such work wants to send are written in its output and sent by the platform on its behalf (propose_apply).

No value a tool is given becomes an option: single values go as --name=value, letter ids after --, each a letter id;
an option's id and label never start with -.

Out of scope: HTTP transport, roots/list, registering in tools automatically; a send retried by the client sends two
letters (the letter id is generated by hubbus). PyYAML (bin/py) for the judgment points' declarations.
"""
