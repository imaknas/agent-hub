class Client:
    """What the client said at initialize, and a way to ask its user directly (MCP elicitation) where it can."""

    def __init__(self):
        self.elicitation, self.next_id = False, 0
        self.pending: list[str] = []   # what arrived while waiting for an answer, for serve() to handle next

    def line(self) -> str:
        return self.pending.pop(0) if self.pending else sys.stdin.readline()

    def confirm(self, message: str) -> bool | None:
        """Ask the user through the client, bypassing the model: True / False, or None when the client can't ask."""
        if not self.elicitation:
            return None
        self.next_id += 1
        rid = f"agenthub-elicit-{self.next_id}"
        send({"jsonrpc": "2.0", "id": rid, "method": "elicitation/create", "params": {
            "message": message, "requestedSchema": {"type": "object", "required": ["connect"], "properties": {
                "connect": {"type": "boolean", "title": _("Connect it")}}}}})
        while (line := sys.stdin.readline()):   # the client's answer; anything else is kept for serve()
            try:
                msg = json.loads(line)
            except ValueError:
                continue
            if msg.get("id") == rid and "method" not in msg:
                res = msg.get("result") or {}
                return res.get("action") == "accept" and (res.get("content") or {}).get("connect") is True
            self.pending.append(line)
        return False


def outside(name: str, args: dict, client: "Client") -> tuple[bool, str]:
    if name == "status":
        known = sorted(hubconf.projects() or {})
        return True, _("brunna is installed. Projects: {names}. Folders may be connected from inside: {roots}.",
                       names=", ".join(known) or _("none yet"),
                       roots=", ".join(map(str, hubconf.project_roots())) or _("nowhere yet"))
    if name != "connect_project":
        return False, _("this folder is not an brunna project: only status and connect_project work here")
    if os.environ.get("HUBBUS_LEASE"):
        return False, _("a lease session can't connect folders")
    import connect
    roots = hubconf.project_roots()
    if (why := connect.in_roots(pathlib.Path(str(args["path"])), roots)):
        return False, why
    real = pathlib.Path(os.path.expanduser(str(args["path"]))).resolve()
    if (why := connect.refusal(real)):
        return False, why
    answer = client.confirm(_("Connect {path} as an brunna project? Its notes are kept in a separate place, a "
                              "folder without version history gets one, no GitHub repo is created, and a first summary "
                              "is written from its README and recent commit titles by the AI model that makes "
                              "brunna's decisions.", path=real))
    if answer is False:
        return False, _("the user declined; nothing was done")
    env = dict(os.environ)
    names.env_set(env, "CONNECT_ROOTS", ":".join(map(str, roots)))
    r = subprocess.run([sys.executable, str(BIN / "connect.py"), str(real), "--yes"], capture_output=True, text=True,
                       timeout=600, env=env)
    out = (r.stdout + ("\n" + r.stderr if r.stderr.strip() else "")).strip()
    tail = "" if answer else "\n" + _("Tell the user what was connected: this client can't ask them directly.")
    return r.returncode == 0, out + tail


def hubbus_cli(project: str, *args: str) -> tuple[bool, str]:
    # a sandboxed project's commands run in its folder, where hubbus takes its outbox and view instead of the bus
    cwd = hubconf.workspace(project) if _hubbus().outboxed(project) else os.getcwd()
    r = subprocess.run([sys.executable, str(BIN / "hubbus"), *args], capture_output=True, text=True, timeout=60,
                       cwd=cwd)
    out = (r.stdout + ("\n" + r.stderr if r.stderr.strip() else "")).strip()
    return r.returncode == 0, out or (_("done") if r.returncode == 0 else f"exit {r.returncode}")


def write_note(project: str, text: str) -> tuple[bool, str]:
    ws = hubconf.workspace(project)
    mem = ws / ".agent-memory" / "memory" if ws else None
    if not mem or not mem.parent.is_dir():
        return False, _("{project} has no memory folder (.agent-memory); this project is not set up for memory tracking",
                         project=project)
    mem.mkdir(exist_ok=True)
    f = mem / f"{datetime.date.today().isoformat()}.md"
    line = " ".join(text.split())
    with f.open("a") as fh:
        fh.write(f"- {line}\n")
    return True, _("written to memory/{file} of {project} (the platform syncs it)", project=project, file=f.name)


def call(project: str | None, why: str, name: str, args: dict, client: "Client | None" = None) -> tuple[bool, str]:
    if os.environ.get("HUB_LLM_POINT"):
        return False, _("This is work the platform started ({point}): write the letters to send and what to close in "
                        "your output; the platform sends them for you. Do not use this server", point=os.environ["HUB_LLM_POINT"])
    if not project:
        if name in ("status", "connect_project") and not names.env("PROJECT"):
            return outside(name, args, client or Client())
        return False, why
    if name == "inbox":
        try:
            n = unread(project)
        except Exception:   # the inbox call below reports what is wrong
            n = 0
        ok, out = hubbus_cli(project, "inbox", "--project", project)
        # a session's `inbox` says what letters are itself; a platform run's doesn't (hubbus.mail_command)
        platform = os.environ.get("HUB_LLM_POINT") or os.environ.get("HUBBUS_LEASE")
        return ok, f"{_hubbus().header(n, project)}\n\n{out}" if n and platform else out
    if name in ("show", "thread"):
        return hubbus_cli(project, name, str(args["id"]))
    if name == "send":
        extra = ["--reply-to", str(args["reply_to"])] if args.get("reply_to") else []
        return hubbus_cli(project, "send", "--from", project, "--to", str(args["to"]), "--type", str(args["type"]),
                          "--text", str(args["text"]), *extra)
    if name == "ack":
        return hubbus_cli(project, "ack", *map(str, args["ids"]))
    if name == "pass":
        return hubbus_cli(project, "pass", *map(str, args["ids"]))
    if name == "done":
        return hubbus_cli(project, "done", *map(str, args["ids"]), *(["--note", str(args["note"])] if args.get("note") else []))
    if name == "ask_owner":
        return hubbus_cli(project, "send", "--from", project, "--to", hubconf.owner_address(), "--type", "question",
                          "--text", str(args["text"]))
    if name == "note":
        return write_note(project, str(args["text"]))
    return False, _("no such tool: {name}", name=name)


def send(msg: dict) -> None:
    sys.stdout.write(json.dumps(msg, ensure_ascii=False) + "\n")
    sys.stdout.flush()


def serve() -> int:
    project, why = resolve_project()
    log(_("project: {project}", project=project or _("(unrecognized)")))
    presence = Presence(project)
    client = Client()
    while (line := client.line()):
        try:
            msg = json.loads(line)
        except ValueError:
            continue
        mid, method = msg.get("id"), msg.get("method")
        if method == "initialize":
            presence.touch("initialize", ((msg.get("params") or {}).get("clientInfo") or {}).get("name"))
            client.elicitation = "elicitation" in (((msg.get("params") or {}).get("capabilities")) or {})
            send({"jsonrpc": "2.0", "id": mid, "result": {
                "protocolVersion": (msg.get("params") or {}).get("protocolVersion") or PROTOCOL,
                "capabilities": {"tools": {}}, "serverInfo": {"name": names.current("cli"), "version": "1"},
                "instructions": instructions(project, why)}})
        elif method == "tools/list":
            # outside every project: what agent-hub is, and connecting the folder (B5); a server named to a project
            # by AGENTHUB_PROJECT keeps the project tools
            send({"jsonrpc": "2.0", "id": mid, "result": {"tools": TOOLS if project else TOOLS_OUTSIDE}})
        elif method == "tools/call":
            params = msg.get("params") or {}
            presence.touch("tool")
            try:
                ok, text = call(project, why, params.get("name", ""), params.get("arguments") or {}, client)
            except (KeyError, TypeError) as e:
                ok, text = False, _("wrong arguments: {e}", e=e)
            except Exception as e:
                ok, text = False, _("platform error: {e!r}", e=e)
            text += notice(project, str(params.get("name", "")))
            send({"jsonrpc": "2.0", "id": mid, "result": {"content": [{"type": "text", "text": text}], "isError": not ok}})
        elif mid is not None:   # ping and the like: empty result; notifications (no id) get no reply
            send({"jsonrpc": "2.0", "id": mid, "result": {}})
    return 0


def config() -> int:
    cli = names.resolve(pathlib.Path.home() / ".local" / "bin", "cli")
    entry = ({"command": str(cli), "args": ["mcp"]} if cli.exists()
             else {"command": str(BIN / "py"), "args": [str(BIN / "agenthub"), "mcp"]})
    print(_("Register this stdio MCP server in your coding agent (start it in the project folder; a tool opened from the "
            "GUI may not have your PATH, hence the absolute paths):\n"))
    print(json.dumps({"mcpServers": {names.current("cli"): entry}}, indent=2))
    print(_("\nHow to add it in each tool: docs/mcp.md. For a tool not started in the project folder, add "
            "AGENTHUB_PROJECT=<project name> to its env."))
    return 0


if __name__ == "__main__":
    if sys.argv[1:] == ["config"]:
        sys.exit(config())
    sys.exit(serve())
