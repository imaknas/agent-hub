def run_tool_list(run: Run) -> list:
    """A run's tools as the client sees them: a job's send starts new letters only (no reply_to, no question, no done or
    drop); a handler's send has question too (the reconciliation close: done or drop)."""
    out, job = [], run.job
    for t in TOOLS:
        if t["name"] not in run.tools:
            continue
        if t["name"] == "send":
            props = {"to": _str("the receiving project's name, or the owner"),
                     "type": {"type": "string", "enum": JOB_TYPES if job else HANDLER_TYPES},
                     "text": _str("the content (full sentences: the recipient cannot see your conversation)")}
            if not job:
                props["reply_to"] = _str("the letter this replies to (its id)")
                props["question"] = _str("the owner's question one of your letters names, closed with type done or drop")
            t = {**t, "description": ("Send a new letter to a project (request, question, info, progress), or a question "
                                      "to the owner." if job else t["description"]),
                 "inputSchema": {"type": "object", "required": ["to", "type", "text"], "properties": props}}
        if t["name"] == "done":
            t = {**t, "description": "Handled: close the letters this run was started for.",
                 "inputSchema": {"type": "object", "required": ["ids"], "properties": {
                     "ids": _ids(), "note": _str("how they were handled")}}}
        out.append(t)
    return out


