def log(msg: str) -> None:
    print(f"{names.current('cli')} mcp: {msg}", file=sys.stderr, flush=True)


def _hubbus():
    loader = importlib.machinery.SourceFileLoader("hubbus_mcp", str(BIN / "hubbus"))
    spec = importlib.util.spec_from_loader("hubbus_mcp", loader)
    m = importlib.util.module_from_spec(spec)
    loader.exec_module(m)
    return m


_HB = []


def hb():
    """hubbus, loaded once (its id shapes; the calls themselves go through its command)."""
    if not _HB:
        _HB.append(_hubbus())
    return _HB[0]


def letter_id(x) -> bool:
    # fullmatch: EVENT_ID ends in $, and .match would let a final newline through
    return isinstance(x, str) and bool(hb().EVENT_ID.fullmatch(x))


def point_spec(point: str) -> dict | None:
    import yaml
    return (yaml.safe_load((BIN.parent / "contracts" / "llm-points.yaml").read_text()).get("points") or {}).get(point)


def run_tools(spec: dict) -> tuple:
    """The tools a confined point's run gets: a mail handler's (it acts on given letters) or a job's."""
    return HANDLER_TOOLS if spec.get("letters_env") else JOB_TOOLS


def notes_base(project: str) -> pathlib.Path | None:
    """The folder a project's notes are under (.agent-memory/memory): its workspace, the main checkout for the hub."""
    return hubconf.MAIN if project == hubconf.hub_project() else hubconf.workspace(project)


class Run:
    """A confined run's file (--run): read once, at start. refusal: why every call is refused (None: it serves)."""

    def __init__(self, path: str):
        self.project = self.point = self.letters = self.chain = self.depth = self.workspace = None
        self.tools, self.refusal, self.job = HANDLER_TOOLS, None, False
        try:
            self._load(pathlib.Path(path))
        except Exception as e:
            self.refusal = _("this run's mail is refused: {why}", why=e)
            log(self.refusal)

    def _load(self, path: pathlib.Path) -> None:
        import stat
        base = pathlib.Path(os.path.realpath(hubconf.STATE / "agent-jobs" / ".settings"))
        folder = pathlib.Path(os.path.realpath(path.parent))
        if not (folder == base or base in folder.parents):
            raise ValueError(_("its file {file} is not in the platform's run folders", file=path))
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC)
        try:
            st = os.fstat(fd)
            if not stat.S_ISREG(st.st_mode) or st.st_uid != os.getuid() or st.st_mode & 0o022:
                raise ValueError(_("its file {file} is not a regular file of this user that only it can write", file=path))
            raw = os.read(fd, RUN_FILE_MAX + 1)
        finally:
            os.close(fd)
        if len(raw) > RUN_FILE_MAX:
            raise ValueError(_("its file {file} is too large", file=path))
        d = json.loads(raw)
        if not isinstance(d, dict):
            raise ValueError(_("its file {file} is not a JSON object", file=path))
        spec = point_spec(str(d.get("point")))
        if not spec or spec.get("mail") != "tools":
            raise ValueError(_("{point} does not declare the mail tools", point=d.get("point")))
        self.point, allowed = d["point"], run_tools(spec)
        self.tools, self.job = allowed, not spec.get("letters_env")
        tools = d.get("tools")
        if not isinstance(tools, list) or not all(isinstance(t, str) and t in allowed for t in tools):
            raise ValueError(_("its tools are not ones {point} gives", point=self.point))
        self.tools = tuple(t for t in allowed if t in tools)
        project = d.get("project")
        if not isinstance(project, str) or project not in (hubconf.projects() or {}):
            raise ValueError(_("{project} is not a registered project", project=project))
        ws = notes_base(project)
        if not ws or not pathlib.Path(ws).is_dir():
            raise ValueError(_("{project} has no folder to send from", project=project))
        if spec.get("letters_env"):
            letters = d.get("letters")
            if not isinstance(letters, list) or not letters or not all(letter_id(i) for i in letters):
                raise ValueError(_("it acts on given letters and its file lists none"))
            self.letters = letters
        for k in ("chain", "depth"):
            if d.get(k) is not None and not isinstance(d[k], str):
                raise ValueError(_("its file's {key} is not text", key=k))
        self.chain, self.depth = d.get("chain"), d.get("depth")
        self.project, self.workspace = project, pathlib.Path(ws)


def run_env(run: Run) -> dict:
    """hubbus's environment for a run's call: built, never inherited whole. None of the platform's variables but those
    set here (no JOB, no chain but the run's, no lease or propose marks), no login, the instance's locations as this
    server has them, and the run's values: confined, its chain, its point and letters (unprefixed: hubbus reads them so).
    The rest of the agent's environment stays, the runtime's session id with it."""
    env = names.env_strip(os.environ)
    for k in list(env):
        if k in UNPREFIXED or k.startswith("AGENT_JOB_"):
            del env[k]
    try:
        import completion
        for k in completion.key_envs():
            env.pop(k, None)
    except Exception:
        pass
    try:
        import runtime_ports
        env = dict(runtime_ports.load(None, ports=("auth",)).clean_env(env))
    except Exception:
        pass
    for k in LOCATIONS:
        if (v := names.env(k)):
            names.env_set(env, k, v)
    names.env_set(env, "CONFINED", "1")
    if run.chain is not None:
        names.env_set(env, "JOB_CHAIN", run.chain)
    if run.depth is not None:
        names.env_set(env, "JOB_DEPTH", run.depth)
    env["HUB_LLM_POINT"] = run.point
    if run.letters is not None:
        env["MAILBOX_LETTERS"] = json.dumps(run.letters, ensure_ascii=False)
    return env


def resolve_project() -> tuple[str | None, str]:
    """(project, the reason shown to people when it cannot be recognised)."""
    if names.env("PROJECT"):
        return names.env("PROJECT"), ""
    try:
        name = _hubbus().project_of(pathlib.Path.cwd())
    except Exception as e:   # initialize must still answer when the platform settings are broken
        return None, _("cannot read the project registry: {e}", e=e)
    if name:
        return name, ""
    return None, _("the working directory {cwd} is not inside any registered project: start this server in the project "
                   "folder, or set the environment variable AGENTHUB_PROJECT=<project name> in the tool's MCP settings",
                   cwd=pathlib.Path.cwd())


def unread(project: str) -> int:
    hb = _hubbus()
    c = hb.mail_db(project)   # a sandboxed project's own view: the bus is in none of its sandboxes
    try:
        return len(hb.inbox(c, project))
    finally:
        c.close()


class Presence:
    """That this server's client uses the project (docs/design/mailbox-runtimes.md A3): written at initialize and at
    each agenthub tool call, so dispatch holds a letter for it instead of sending another agent onto the project. stdio
    MCP has no session id, so the id is mcp:<this process's pid>:<its start time> (a session id the runtime gives in
    this process's environment is used instead). Not written for agents the platform started (HUB_LLM_POINT) or lease
    sessions (HUBBUS_LEASE), nor by a server whose project comes from AGENTHUB_PROJECT while its working directory is
    outside that project: one global server in a tool must not keep a project in use for good."""

    EVERY_S = 60   # the same kind of write at most this often (a sandboxed project's goes through a file per write)

    def __init__(self, project: str | None):
        self.project, self.sid, self.client, self.last = project, None, None, (None, 0.0)
        if not project or os.environ.get("HUB_LLM_POINT") or os.environ.get("HUBBUS_LEASE"):
            return
        self.hb = _hubbus()
        named = names.env("PROJECT")
        if named:
            try:
                here = self.hb.project_of(pathlib.Path.cwd())
            except Exception:
                here = None
            if here != named:
                log(_("presence not recorded: the working directory {cwd} is not in {project} (named by "
                      "AGENTHUB_PROJECT), so dispatch is not held for this server", cwd=pathlib.Path.cwd(), project=named))
                return
        import runtime_ports
        try:
            sid = runtime_ports.current_session()
        except Exception:   # broken platform settings: the synthetic id below still holds dispatch back
            sid = None
        if sid:
            self.sid = sid
            return
        start = self.hb.proc_start(os.getpid())
        if not start:
            log(_("presence not recorded: cannot read this process's start time, so dispatch is not held for this "
                  "server"))
            return
        self.sid = f"mcp:{os.getpid()}:{start}"

    def touch(self, via: str, client=None) -> None:
        if client:
            self.client = client
        if not self.sid or (self.last[0] == via and time.monotonic() - self.last[1] < self.EVERY_S):
            return
        try:
            self.hb.mcp_presence(self.project, self.sid, pathlib.Path.cwd(), self.client, via)
            self.last = (via, time.monotonic())
        except Exception as e:   # never in the way of the call itself
            log(_("cannot record presence: {e!r}", e=e))


def notice(project: str | None, name: str) -> str:
    """Appended to an agenthub tool's result: how many letters are open, so a session told only through MCP knows
    the platform is holding them for it (inbox shows them itself). A sandboxed project's count is from its view."""
    if not project or name == "inbox" or os.environ.get("HUB_LLM_POINT"):
        return ""
    try:
        n = unread(project)
    except Exception:
        return ""
    return "\n\n" + _("📬 {n} {n:letter is|letters are} still open; look with inbox first.", n=n) if n else ""


def instructions(project: str | None, why: str) -> str:
    text = INSTRUCTIONS.read_text()
    if not project:
        return prompts.fill(text, project=_("(unrecognized)"), take_timeout=60, unread=f"⚠️ {why}\n" + _(
            "Outside a project, the tools here are status (what brunna has) and connect_project: when the user asks "
            "to connect this folder to brunna, call it with the folder's absolute path."))
    hb = _hubbus()
    try:
        n = unread(project)
        line = _("📬 {n} {n:letter is|letters are} still open; look with inbox first.", n=n) if n else _("📭 No open letters now.")
    except Exception as e:
        line = _("(cannot read the mailbox: {e})", e=e)
    return prompts.fill(text, project=project, unread=line, take_timeout=hb.TAKE_TIMEOUT_MIN)


