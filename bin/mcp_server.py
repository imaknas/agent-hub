class Client:
    """What the client said at initialize, and a way to ask its user directly (MCP elicitation) where it can."""

    def __init__(self):
        self.elicitation, self.next_id = False, 0
        self.pending: list[str] = []   # what arrived while waiting for an answer, for serve() to handle next

    def line(self) -> str:
        return self.pending.pop(0) if self.pending else sys.stdin.readline()

    def confirm(self, message: str) -> bool | None:
        """Ask the user through the client, bypassing the model: True / False, or None when the client can't ask."""
        if not self.elicitation:
            return None
        self.next_id += 1
        rid = f"agenthub-elicit-{self.next_id}"
        send({"jsonrpc": "2.0", "id": rid, "method": "elicitation/create", "params": {
            "message": message, "requestedSchema": {"type": "object", "required": ["connect"], "properties": {
                "connect": {"type": "boolean", "title": _("Connect it")}}}}})
        while (line := sys.stdin.readline()):   # the client's answer; anything else is kept for serve()
            try:
                msg = json.loads(line)
            except ValueError:
                continue
            if msg.get("id") == rid and "method" not in msg:
                res = msg.get("result") or {}
                return res.get("action") == "accept" and (res.get("content") or {}).get("connect") is True
            self.pending.append(line)
        return False


def outside(name: str, args: dict, client: "Client") -> tuple[bool, str]:
    if name == "status":
        known = sorted(hubconf.projects() or {})
        return True, _("brunna is installed. Projects: {names}. Folders may be connected from inside: {roots}.",
                       names=", ".join(known) or _("none yet"),
                       roots=", ".join(map(str, hubconf.project_roots())) or _("nowhere yet"))
    if name != "connect_project":
        return False, _("this folder is not an brunna project: only status and connect_project work here")
    if os.environ.get("HUBBUS_LEASE"):
        return False, _("a lease session can't connect folders")
    import connect
    roots = hubconf.project_roots()
    if (why := connect.in_roots(pathlib.Path(str(args["path"])), roots)):
        return False, why
    real = pathlib.Path(os.path.expanduser(str(args["path"]))).resolve()
    if (why := connect.refusal(real)):
        return False, why
    answer = client.confirm(_("Connect {path} as an brunna project? Its notes are kept in a separate place, a "
                              "folder without version history gets one, no GitHub repo is created, and a first summary "
                              "is written from its README and recent commit titles by the AI model that makes "
                              "brunna's decisions.", path=real))
    if answer is False:
        return False, _("the user declined; nothing was done")
    env = dict(os.environ)
    names.env_set(env, "CONNECT_ROOTS", ":".join(map(str, roots)))
    r = subprocess.run([sys.executable, str(BIN / "connect.py"), str(real), "--yes"], capture_output=True, text=True,
                       timeout=600, env=env)
    out = (r.stdout + ("\n" + r.stderr if r.stderr.strip() else "")).strip()
    tail = "" if answer else "\n" + _("Tell the user what was connected: this client can't ask them directly.")
    return r.returncode == 0, out + tail


def hubbus_cli(project: str, *args: str, run: "Run | None" = None) -> tuple[bool, str]:
    # in the project's folder, so hubbus knows which project asks whatever folder the server started in (names.env("PROJECT")):
    # a sandboxed project's commands take its outbox and view there instead of the bus. A run's: its own folder only, and
    # an environment built for it
    if run is not None:
        cwd, env = run.workspace, run_env(run)
    else:
        ws = hubconf.workspace(project)
        cwd, env = (ws if _hubbus().outboxed(project) or (ws and pathlib.Path(ws).is_dir()) else os.getcwd()), None
    r = subprocess.run([sys.executable, str(BIN / "hubbus"), *args], capture_output=True, text=True, timeout=60,
                       cwd=cwd, env=env)
    out = (r.stdout + ("\n" + r.stderr if r.stderr.strip() else "")).strip()
    return r.returncode == 0, out or (_("done") if r.returncode == 0 else f"exit {r.returncode}")


def write_note(project: str, text: str) -> tuple[bool, str]:
    """Into the project's notes for today, through folders opened without following a link the project planted (a
    `memory/<day>.md -> ~/.zshenv` would otherwise take a line), and only into a file with one link."""
    import nofollow
    import policy
    base = notes_base(project)
    if not base or not policy.notes_dir(project):
        return False, _("{project} has no memory folder (.agent-memory); this project is not set up for memory tracking",
                         project=project)
    name = f"{datetime.date.today().isoformat()}.md"
    line = " ".join(text.split())
    try:
        nofollow.append(base, f".agent-memory/memory/{name}", f"- {line}\n".encode())
    except OSError as e:
        return False, _("the note was not written: {e}", e=e)
    return True, _("written to memory/{file} of {project} (the platform syncs it)", project=project, file=name)


class BadArgs(Exception):
    pass


def _text(args: dict, key: str, required: bool = True) -> str | None:
    v = args.get(key)
    if v is None and not required:
        return None
    if not isinstance(v, str):
        raise BadArgs(_("{key} must be text", key=key))
    return v


def _letter_ids(args: dict) -> list[str]:
    ids = args.get("ids")
    if not isinstance(ids, list) or not ids or not all(isinstance(i, str) for i in ids):
        raise BadArgs(_("ids must be a list of letter ids"))
    if (bad := [i for i in ids if not letter_id(i)]):
        raise BadArgs(_("not a letter id: {id!r}", id=bad[0]))
    return ids


def _one_id(args: dict) -> str:
    i = _text(args, "id")
    if not letter_id(i):
        raise BadArgs(_("not a letter id: {id!r}", id=i))
    return i


def _options(args: dict) -> list[str]:
    opts = args.get("options") or []
    if not isinstance(opts, list) or not all(isinstance(o, dict) for o in opts):
        raise BadArgs(_("options must be a list of objects with id and label"))
    out = []
    for o in opts:
        oid, label = o.get("id", ""), o.get("label", "")
        if not isinstance(oid, str) or not isinstance(label, str):
            raise BadArgs(_("options must be a list of objects with id and label"))
        # --option takes two words: neither may be read as an option itself
        if not hb().OPTION_ID.fullmatch(oid) or oid.startswith("-") or label.startswith("-"):
            raise BadArgs(_("an option's id is a short word without spaces, and neither it nor its label starts with -"))
        out += ["--option", oid, label]
    return out


def mail_args(project: str, name: str, args: dict, run: "Run | None" = None) -> list[str]:
    """The hubbus command for a tool call: single values as --name=value, letter ids after --, so no value is read as an
    option. A run's send is held to its tools' fields (hubbus holds the same line)."""
    if not isinstance(args, dict):
        raise BadArgs(_("the arguments must be an object"))
    if name == "inbox":
        return ["inbox", f"--project={project}"]
    if name in ("show", "thread"):
        return [name, "--", _one_id(args)]
    if name == "send":
        typ = _text(args, "type")
        job = run is not None and run.job
        allowed = TYPES if run is None else JOB_TYPES if job else HANDLER_TYPES
        if typ not in allowed:
            raise BadArgs(_("type must be one of {types}", types=", ".join(allowed)))
        out = ["send", f"--from={project}", f"--to={_text(args, 'to')}", f"--type={typ}", f"--text={_text(args, 'text')}"]
        if (r := _text(args, "reply_to", required=False)):
            if job:
                raise BadArgs(_("this run starts new letters only (no reply_to)"))
            if not letter_id(r):
                raise BadArgs(_("not a letter id: {id!r}", id=r))
            out.append(f"--reply-to={r}")
        if (q := _text(args, "question", required=False)):
            if run is None or job:
                raise BadArgs(_("no such field: question"))
            if not letter_id(q):
                raise BadArgs(_("not a letter id: {id!r}", id=q))
            out.append(f"--question={q}")
        return out
    if name in ("ack", "pass"):
        return [name, "--", *_letter_ids(args)]
    if name == "done":
        ids = _letter_ids(args)
        note = _text(args, "note", required=False)
        withdraw = args.get("withdraw")
        if withdraw is not None and not isinstance(withdraw, bool):
            raise BadArgs(_("withdraw must be true or false"))
        if withdraw and run is not None:
            raise BadArgs(_("this run closes only the letters it was started for (no withdraw)"))
        return ["done", *([f"--note={note}"] if note else []), *(["--withdraw"] if withdraw else []), "--", *ids]
    if name == "ask_owner":
        default = args.get("default")
        if default is not None and not isinstance(default, str):
            raise BadArgs(_("default must be text"))
        return ["send", f"--from={project}", f"--to={hubconf.owner_address()}", "--type=question",
                f"--text={_text(args, 'text')}", *_options(args), *([f"--default={default}"] if default is not None else [])]
    raise BadArgs(_("no such tool: {name}", name=name))


def run_call(run: Run, name: str, args: dict) -> tuple[bool, str]:
    """A confined run's call: its file read and checked at start; its project the file's, its folder checked again; its
    tools the file's (ack, pass and open-questions are never among them)."""
    if run.refusal:
        return False, run.refusal
    if name not in run.tools:
        return False, _("this run has no tool {name}", name=name)
    try:
        here = hb().project_of(run.workspace)
    except Exception as e:
        return False, _("cannot tell which project {folder} is: {e}", folder=run.workspace, e=e)
    if here != run.project:
        return False, _("{folder} is not {project}'s folder; this run's mail is refused", folder=run.workspace,
                        project=run.project)
    if name == "note":
        return write_note(run.project, _text(args, "text"))
    return hubbus_cli(run.project, *mail_args(run.project, name, args, run), run=run)


def call(project: str | None, why: str, name: str, args: dict, client: "Client | None" = None,
         run: "Run | None" = None) -> tuple[bool, str]:
    if run is not None:   # first: before anything that reads the folder or runs connect.py as the user
        try:
            return run_call(run, name, args)
        except BadArgs as e:
            return False, _("wrong arguments: {e}", e=e)
    if os.environ.get("HUB_LLM_POINT"):
        return False, _("This is work the platform started ({point}): write the letters to send and what to close in "
                        "your output; the platform sends them for you. Do not use this server", point=os.environ["HUB_LLM_POINT"])
    if not project:
        if name in ("status", "connect_project") and not names.env("PROJECT"):
            return outside(name, args, client or Client())
        return False, why
    if name not in {t["name"] for t in TOOLS}:
        return False, _("no such tool: {name}", name=name)
    try:
        if name == "note":
            return write_note(project, _text(args, "text"))
        cmd = mail_args(project, name, args)
    except BadArgs as e:
        return False, _("wrong arguments: {e}", e=e)
    if name == "inbox":
        try:
            n = unread(project)
        except Exception:   # the inbox call below reports what is wrong
            n = 0
        ok, out = hubbus_cli(project, *cmd)
        # a session's `inbox` says what letters are itself; a platform run's doesn't (hubbus.mail_command)
        platform = os.environ.get("HUB_LLM_POINT") or os.environ.get("HUBBUS_LEASE")
        return ok, f"{_hubbus().header(n, project)}\n\n{out}" if n and platform else out
    return hubbus_cli(project, *cmd)


def send(msg: dict) -> None:
    sys.stdout.write(json.dumps(msg, ensure_ascii=False) + "\n")
    sys.stdout.flush()


def serve(run_file: str | None = None) -> int:
    # a run's file is read once, here, before initialize: before the model can act
    run = Run(run_file) if run_file is not None else None
    if run is not None:
        project, why = run.project, run.refusal or ""
    else:
        project, why = resolve_project()
    log(_("project: {project}", project=project or _("(unrecognized)")))
    presence = Presence(None if run is not None else project)
    client = Client()
    while (line := client.line()):
        try:
            msg = json.loads(line)
        except ValueError:
            continue
        mid, method = msg.get("id"), msg.get("method")
        if method == "initialize":
            presence.touch("initialize", ((msg.get("params") or {}).get("clientInfo") or {}).get("name"))
            client.elicitation = "elicitation" in (((msg.get("params") or {}).get("capabilities")) or {})
            send({"jsonrpc": "2.0", "id": mid, "result": {
                "protocolVersion": (msg.get("params") or {}).get("protocolVersion") or PROTOCOL,
                "capabilities": {"tools": {}}, "serverInfo": {"name": names.current("cli"), "version": "1"},
                "instructions": RUN_INSTRUCTIONS if run is not None else instructions(project, why)}})
        elif method == "tools/list":
            # outside every project: what agent-hub is, and connecting the folder (B5); a server named to a project
            # by AGENTHUB_PROJECT keeps the project tools. A run: its own
            tools = run_tool_list(run) if run is not None else TOOLS if project else TOOLS_OUTSIDE
            send({"jsonrpc": "2.0", "id": mid, "result": {"tools": tools}})
        elif method == "tools/call":
            params = msg.get("params") or {}
            presence.touch("tool")
            try:
                ok, text = call(project, why, params.get("name", ""), params.get("arguments") or {}, client, run)
            except (KeyError, TypeError) as e:
                ok, text = False, _("wrong arguments: {e}", e=e)
            except Exception as e:
                ok, text = False, _("platform error: {e!r}", e=e)
            if run is None:
                text += notice(project, str(params.get("name", "")))
            send({"jsonrpc": "2.0", "id": mid, "result": {"content": [{"type": "text", "text": text}], "isError": not ok}})
        elif mid is not None:   # ping and the like: empty result; notifications (no id) get no reply
            send({"jsonrpc": "2.0", "id": mid, "result": {}})
    return 0


def config() -> int:
    cli = names.resolve(pathlib.Path.home() / ".local" / "bin", "cli")
    entry = ({"command": str(cli), "args": ["mcp"]} if cli.exists()
             else {"command": str(BIN / "py"), "args": [str(BIN / "agenthub"), "mcp"]})
    print(_("Register this stdio MCP server in your coding agent (start it in the project folder; a tool opened from the "
            "GUI may not have your PATH, hence the absolute paths):\n"))
    print(json.dumps({"mcpServers": {names.current("cli"): entry}}, indent=2))
    print(_("\nHow to add it in each tool: docs/mcp.md. For a tool not started in the project folder, add "
            "AGENTHUB_PROJECT=<project name> to its env."))
    return 0


if __name__ == "__main__":
    if sys.argv[1:] == ["config"]:
        sys.exit(config())
    if sys.argv[1:2] == ["--run"] and len(sys.argv) == 3:
        sys.exit(serve(sys.argv[2]))
    if sys.argv[1:]:
        sys.exit(_("usage: {cli} mcp [config | --run <file>]", cli=names.current("cli")))
    sys.exit(serve())
